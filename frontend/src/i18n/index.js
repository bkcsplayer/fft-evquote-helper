function interpolate(text, vars) {
  if (!vars) return text
  return String(text).replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])))
}

function detectDefaultLang() {
  const nav = (navigator.language || '').toLowerCase()
  if (nav.startsWith('zh')) return 'zh'
  return 'en'
}

const I18nContext = createContext({
  lang: 'en',
  setLang: () => {},
  t: (k) => k,
  toggle: () => {},
})

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem(STORAGE_KEY) || detectDefaultLang())

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang)
  }, [lang])

  const api = useMemo(() => {
    function t(key, vars) {
      const dict = dictionaries[lang] || dictionaries.en
      const raw = dict[key] ?? dictionaries.en[key] ?? key
      return interpolate(raw, vars)
    }
    function toggle() {
      setLang((prev) => (prev === 'zh' ? 'en' : 'zh'))
    }
    // BCP-47 locale for Intl date/number formatting (not text — safe to derive from lang).
    const locale = lang === 'zh' ? 'zh-CN' : 'en-CA'
    return { lang, setLang, t, toggle, locale }
  }, [lang])

  return createElement(I18nContext.Provider, { value: api }, children)
}

export function useI18n() {
  return useContext(I18nContext)
}

